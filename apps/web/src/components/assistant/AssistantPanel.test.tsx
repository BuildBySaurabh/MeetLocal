import { cleanup, fireEvent, render, screen } from '@testing-library/react';
import { afterEach, describe, expect, it, vi } from 'vitest';
import type { AssistantState } from '../../features/assistant/assistant.types';
import { AssistantPanel } from './AssistantPanel';

afterEach(cleanup);

const base: AssistantState = {
  status: 'ready',
  endpoint: 'http://localhost:11434',
  models: ['llama3.2:latest'],
  model: 'llama3.2:latest',
  turns: [],
  generating: false,
  error: null,
};
const segs = [
  { id: '1', startedAt: 1, endedAt: 2, text: 'first line', speaker: 'you' as const },
  { id: '2', startedAt: 3, endedAt: 4, text: 'second line', speaker: 'you' as const },
];

function renderPanel(state: Partial<AssistantState> = {}, segments = segs) {
  const h = { onRun: vi.fn(), onCancel: vi.fn(), onRefresh: vi.fn(), onSetModel: vi.fn(), onClearHistory: vi.fn() };
  render(<AssistantPanel state={{ ...base, ...state }} segments={segments} {...h} />);
  return h;
}

describe('AssistantPanel', () => {
  it('states that it is local and optional', () => {
    renderPanel();
    expect(screen.getByText(/Nothing is sent to a cloud AI service/)).toBeTruthy();
  });

  it('shows install guidance when the model server is unavailable and disables tasks', () => {
    const h = renderPanel({ status: 'unavailable', models: [], model: null });
    expect(screen.getByRole('alert').textContent).toMatch(/not available/);
    expect(screen.getByRole('alert').textContent).toMatch(/ollama pull/);
    expect((screen.getByRole('button', { name: 'Summarize' }) as HTMLButtonElement).disabled).toBe(true);
    fireEvent.click(screen.getByRole('button', { name: /check again/i }));
    expect(h.onRefresh).toHaveBeenCalled();
  });

  it.each([
    ['no-model', /no models installed/],
    ['model-missing', /is not installed/],
    ['blocked-endpoint', /not on this computer/],
  ] as const)('explains the %s state', (status, pattern) => {
    renderPanel({ status, model: 'llama3.2' });
    expect(screen.getByRole('alert').textContent).toMatch(pattern);
  });

  it('runs a task only on the selected lines', () => {
    const h = renderPanel();
    fireEvent.click(screen.getByLabelText('second line'));
    fireEvent.click(screen.getByRole('button', { name: 'Summarize' }));
    expect(h.onRun).toHaveBeenCalledWith('summary', [segs[0]]);
    expect(screen.getByText('1 of 2 selected')).toBeTruthy();
  });

  it('disables tasks with nothing selected or no transcript', () => {
    renderPanel();
    fireEvent.click(screen.getByRole('button', { name: 'Select none' }));
    expect((screen.getByRole('button', { name: 'Summarize' }) as HTMLButtonElement).disabled).toBe(true);
    cleanup();
    renderPanel({}, []);
    expect(screen.getByText(/no transcript yet/i)).toBeTruthy();
  });

  it('asks a question and labels answers as generated', () => {
    const h = renderPanel({
      turns: [
        {
          id: 't',
          task: 'summary',
          prompt: 'Summarize',
          answer: 'Ignore <b>this</b>',
          model: 'llama3.2:latest',
          sourceCount: 2,
          createdAt: 1,
        },
      ],
    });
    fireEvent.change(screen.getByLabelText(/question about/i), { target: { value: 'Who?' } });
    fireEvent.click(screen.getByRole('button', { name: 'Ask' }));
    expect(h.onRun).toHaveBeenCalledWith('ask', segs, 'Who?');
    expect(screen.getByText(/Generated by llama3.2:latest on this device from 2 selected lines/)).toBeTruthy();
    expect(screen.getByText('Ignore <b>this</b>')).toBeTruthy();
    fireEvent.click(screen.getByRole('button', { name: /clear assistant history/i }));
    expect(h.onClearHistory).toHaveBeenCalled();
  });

  it('offers stop while generating', () => {
    const h = renderPanel({ generating: true });
    fireEvent.click(screen.getByRole('button', { name: /stop/i }));
    expect(h.onCancel).toHaveBeenCalled();
  });
});
